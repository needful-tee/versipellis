// Package browser is an updated and slimmer version of github.com/pkg/browser.
// It supports opening URLs in local web browsers across different operating systems.
// This is used to enable interactive 3-legged OAuth 2 "Authorization Code" flows.
// This package is inherently non-hermetic, so its tests are not included in CI.
package browser

import (
	"context"
	"fmt"
	"os/exec"
)

type (
	// Opener opens a URL on behalf of the user, instead of a web browser (see [WithOpener]).
	Opener    func(ctx context.Context, url string) error
	openerKey struct{}
)

// WithOpener returns a copy of the given context which makes [OpenURL] call the given function instead
// of starting a web browser. This enables headless interactive flows in tests that act as the user.
func WithOpener(ctx context.Context, fn Opener) context.Context {
	return context.WithValue(ctx, openerKey{}, fn)
}

// OpenURL opens the specified URL in the default web browser for the current operating system,
// or with an [Opener] function embedded in the given context, if it has one (see [WithOpener]).
// This is intended only for trusted URLs, i.e. hardcoded/allow-listed/generated/sanitized.
func OpenURL(ctx context.Context, url string) error {
	if fn, ok := ctx.Value(openerKey{}).(Opener); ok && fn != nil {
		return fn(ctx, url)
	}
	return startBrowser(ctx, url)
}

// runCmd starts the given command without waiting for it to exit, because some browser launchers (e.g.,
// "x-www-browser" on Linux) run the browser itself in the foreground, until the user closes it. For the same
// reason, the context is checked only before starting the command: canceling it must not kill the user's browser.
func runCmd(ctx context.Context, name string, args ...string) error {
	if err := ctx.Err(); err != nil {
		return fmt.Errorf("not starting %q: %w", name, err)
	}

	ctx = context.WithoutCancel(ctx)
	cmd := exec.CommandContext(ctx, name, args...) //gosec:disable G204 // Name and args are hardcoded/generated by us.
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("command execution error for %q: %w", name, err)
	}
	go func() { _ = cmd.Wait() }() // Release process resources when it exits.
	return nil
}
